package create

import (
	"context"
	"fmt"
	"time"

	"github.com/spf13/cobra"
	scf "github.com/stackitcloud/stackit-sdk-go/services/scf/v1api"

	"github.com/stackitcloud/stackit-cli/internal/pkg/args"
	cliErr "github.com/stackitcloud/stackit-cli/internal/pkg/errors"
	"github.com/stackitcloud/stackit-cli/internal/pkg/examples"
	"github.com/stackitcloud/stackit-cli/internal/pkg/globalflags"
	"github.com/stackitcloud/stackit-cli/internal/pkg/print"
	"github.com/stackitcloud/stackit-cli/internal/pkg/services/scf/client"
	"github.com/stackitcloud/stackit-cli/internal/pkg/tables"
	"github.com/stackitcloud/stackit-cli/internal/pkg/types"
	"github.com/stackitcloud/stackit-cli/internal/pkg/utils"
)

const (
	orgIdArg = "ORGANIZATION_ID"
)

type inputModel struct {
	*globalflags.GlobalFlagModel
	OrganizationId string
}

func NewCmd(p *types.CmdParams) *cobra.Command {
	cmd := &cobra.Command{
		Use:   fmt.Sprintf("create %s", orgIdArg),
		Short: "Creates an organization manager for a STACKIT Cloud Foundry organization",
		Long: "Creates an organization manager for a STACKIT Cloud Foundry organization.\n" +
			"The username and password are generated by the API and shown only once in the command output.",
		Args: args.SingleArg(orgIdArg, utils.ValidateUUID),
		Example: examples.Build(
			examples.NewExample(
				`Create an organization manager for a STACKIT Cloud Foundry organization with ID "xxx"`,
				`$ stackit beta scf organization manager create xxx`),
		),
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx := context.Background()
			model, err := parseInput(p.Printer, cmd, args)
			if err != nil {
				return err
			}

			// Configure API client
			apiClient, err := client.ConfigureClient(p.Printer, p.CliVersion)
			if err != nil {
				return err
			}

			prompt := fmt.Sprintf("Are you sure you want to create an organization manager for STACKIT Cloud Foundry organization %q?", model.OrganizationId)
			err = p.Printer.PromptForConfirmation(prompt)
			if err != nil {
				return err
			}

			// Call API
			req := buildRequest(ctx, model, apiClient.DefaultAPI)
			resp, err := req.Execute()
			if err != nil {
				return fmt.Errorf("create STACKIT Cloud Foundry organization manager: %w", err)
			}

			return outputResult(p.Printer, model.OutputFormat, resp)
		},
	}
	return cmd
}

func parseInput(p *print.Printer, cmd *cobra.Command, inputArgs []string) (*inputModel, error) {
	organizationId := inputArgs[0]

	globalFlags := globalflags.Parse(p, cmd)
	if globalFlags.ProjectId == "" {
		return nil, &cliErr.ProjectIdError{}
	}

	model := inputModel{
		GlobalFlagModel: globalFlags,
		OrganizationId:  organizationId,
	}

	p.DebugInputModel(model)
	return &model, nil
}

func buildRequest(ctx context.Context, model *inputModel, apiClient scf.DefaultAPI) scf.ApiCreateOrgManagerRequest {
	return apiClient.CreateOrgManager(ctx, model.ProjectId, model.Region, model.OrganizationId)
}

func outputResult(p *print.Printer, outputFormat string, manager *scf.OrgManagerResponse) error {
	return p.OutputResult(outputFormat, manager, func() error {
		if manager == nil {
			return fmt.Errorf("received nil response, could not display organization manager")
		}

		p.Outputf("Created organization manager for STACKIT Cloud Foundry organization %q. The password is shown only once.\n", manager.GetOrgId())

		table := tables.NewTable()
		table.SetHeader("Attribute", "Value")

		table.AddRow("Username", manager.GetUsername())
		table.AddRow("Password", manager.GetPassword())
		table.AddRow("ID", manager.GetGuid())
		table.AddRow("Organization ID", manager.GetOrgId())
		table.AddRow("Platform ID", manager.GetPlatformId())
		table.AddRow("Project ID", manager.GetProjectId())
		table.AddRow("Region", manager.GetRegion())
		table.AddRow("Created", manager.CreatedAt.Format(time.DateTime))

		err := table.Display(p)
		if err != nil {
			return fmt.Errorf("render table: %w", err)
		}

		return nil
	})
}
